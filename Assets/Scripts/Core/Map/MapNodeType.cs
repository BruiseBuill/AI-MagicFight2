namespace MagicBrawl.Core
{
    /// <summary>
    /// 地图节点的类型（2026-10-02 · 冒险地图）。
    ///
    /// <para><b>口径</b>（用户 2026-10-02）：起点<b>固定</b>是 <see cref="Camp"/>、
    /// 终点<b>固定</b>是 <see cref="Boss"/>，中间随机。所以这个枚举既是「节点是什么」，
    /// 也是「进去之后会发生什么」的**唯一分类依据** ——
    /// 表现层只按它查表决定「有没有对应场景」（见 <c>MapSceneRoutes</c>），
    /// <b>不在别处再判一遍</b>（铁律 3 的落法）。</para>
    ///
    /// <para><b>2026-10-09 追加第 9 项 <see cref="Rest"/></b>（休息事件 —— 用户给了图标、
    /// 也明确要的场景，所以不是猜出来的机制）。此前那句「没有 Rest」说的是<b>当轮</b>的事实：
    /// 那轮只给了 7 张节点图（营地 / 战斗 / 商店 / 女巫 / 石台 / 未知 / Boss），
    /// 「营地」被指定为<b>起点</b>，休息机制还没做。现在补上了 ——
    /// 这不是推翻旧决定，只是把「将来做休息点时再加一项」这件事做了。</para>
    ///
    /// <para><b>2026-10-09 追加第 8 项 <see cref="Treasure"/></b>（≠ 上面那条「不凭空造」——
    /// 那一项是<b>用户给了图、也明确要的场景</b>，不是猜出来的机制）。</para>
    /// </summary>
    public enum MapNodeType
    {
        /// <summary>营地 —— <b>起点</b>专用。没有对应场景（玩家从这里出发）。</summary>
        Camp = 0,

        /// <summary>普通战斗 —— 进战斗场景。</summary>
        Battle = 1,

        /// <summary>商店 —— 进商店场景。</summary>
        Shop = 2,

        /// <summary>女巫的工坊 —— 进女巫工坊场景（献祭一张牌换效果转移）。</summary>
        Witch = 3,

        /// <summary>石台 —— 进强化场景（力量 +2）。</summary>
        Altar = 4,

        /// <summary>未知 —— 事件占位。<b>本轮没有对应场景</b>，进去只是「到此一游」。</summary>
        Unknown = 5,

        /// <summary>Boss —— <b>终点</b>专用。进战斗场景，赢了算通关。</summary>
        Boss = 6,

        /// <summary>
        /// 宝箱 —— 进宝箱事件场景：点开箱子拿一笔金币（用户 2026-10-09 追加的第 8 种节点）。
        ///
        /// <para><b>⚠ 为什么新加一项而不是复用 <see cref="Unknown"/></b>：用户口径是
        /// 「额外增加一个宝箱事件场景」——「未知」那张图与那个占位语义仍然保留，
        /// 两者并列出现在中间层。所以这里<b>追加在末尾</b>（值 = 7），
        /// 既有 7 个成员的值一个都不动，已经存过值的地方（节点图数组的下标）不会被错位。</para>
        ///
        /// <para>金币数额不在这里 —— 那是内容（<c>UiLayout.TreasureGoldGain</c> 现在给 50，
        /// 将来搬进冒险配置）。这里只是「进去会发生什么」的<b>分类依据</b>。</para>
        /// </summary>
        Treasure = 7,

        /// <summary>
        /// 休息 —— 进休息事件场景：点一下把当前生命与生命上限一并<b>恢复满</b>
        /// （用户 2026-10-09 追加的第 9 种节点）。
        ///
        /// <para><b>⚠ 为什么新加一项而不是复用 <see cref="Camp"/></b>：<see cref="Camp"/>
        /// 是<b>起点</b>专用（「玩家从这里出发」，没有场景）；休息是路上可以走进去的一个
        /// <b>事件</b>（有场景、有交互）。两者的语义、场景、图标都不同，合并会把
        /// 「起点」这件事弄脏。</para>
        ///
        /// <para>⚠ 与 <see cref="Treasure"/> 同口径：<b>追加在末尾</b>（值 = 8），
        /// 既有 8 个成员的值一个都不动 —— 已经存过值的地方（节点图数组的下标）不会被错位。</para>
        ///
        /// <para>恢复多少不在这里 —— 它是内容（<c>MapRun.RestoreFullHp</c> 把当前生命写成
        /// <c>MapRun.DefaultHp</c>）。这里只是「进去会发生什么」的<b>分类依据</b>。</para>
        /// </summary>
        Rest = 8,
    }
}
